def prompt_policy(db, user):
    row = db.scalar(
        select(UserSettings)
        .where(UserSettings.user_id == user.id, UserSettings.tenant_id == user.tenant_id)
        .execution_options(populate_existing=True)
    )
    saved = (row.value.get("news_system_prompt") or {}) if row else {}
    text = saved.get("text") or DEFAULT_PROMPT
    return {
        "version": saved.get("version", 1),
        "text": text,
        "sha256": hashlib.sha256(text.encode()).hexdigest(),
        "updated_at": saved.get("updated_at"),
        "default_text": DEFAULT_PROMPT,
        "admin_id": user.id,
    }
